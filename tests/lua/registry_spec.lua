local H = dofile("tests/lua/helper.lua")

describe("Registry", function()
  local ns
  before_each(function() ns = H.load() end)

  it("enregistre un guide et le retrouve", function()
    local g = Sentier:NewGuide("rep-a", { title = "A", category = "Réputation" })
    assert.are.equal(g, ns.Registry:Get("rep-a"))
  end)

  it("trie les guides par catégorie puis par titre", function()
    Sentier:NewGuide("m", { title = "Montures", category = "Montures" })
    Sentier:NewGuide("b", { title = "Tribu", category = "Réputation" })
    Sentier:NewGuide("a", { title = "Hara’ti", category = "Réputation" })
    local ids = {}
    for _, g in ipairs(ns.Registry:List()) do ids[#ids + 1] = g.id end
    assert.are.same({ "m", "a", "b" }, ids)
  end)

  it("retombe sur le premier guide si l'identifiant mémorisé n'existe plus", function()
    Sentier:NewGuide("b", { title = "B", category = "R" })
    Sentier:NewGuide("a", { title = "A", category = "R" })
    assert.are.equal("b", ns.Registry:Resolve("b").id)
    assert.are.equal("a", ns.Registry:Resolve("ancien-guide").id)
    assert.are.equal("a", ns.Registry:Resolve(nil).id)
  end)

  it("n'a aucun guide à proposer quand rien n'est enregistré", function()
    assert.is_nil(ns.Registry:Resolve("x"))
  end)

  it("complète une quête avec le catalogue et la faction du guide", function()
    local g = Sentier:NewGuide("rep-a", {
      title = "A", category = "R", faction = 2696,
      catalog = { [100] = { title = "La chasse attend", zone = "Harandar" } },
    })
    local t = g:Quest(100, { rep = 250 })
    assert.are.equal("La chasse attend", t.title)
    assert.are.equal("Harandar", t.zone)
    assert.are.same({ 2696 }, t.factions)
    assert.are.same({ 100 }, t.questIds)
    assert.are.equal("sidequests", t.source)
    assert.are.equal("none", t.reset)
    assert.are.equal("100", t.key)
    assert.are.equal(250, t.rep)
  end)

  it("signale une quête absente du catalogue", function()
    local g = Sentier:NewGuide("rep-a", { title = "A", category = "R" })
    g:Quest(999, {})
    assert.is_true(H.hasProblem(ns, "Quête absente du catalogue : 999"))
  end)

  it("marque manquante une quête absente du catalogue", function()
    local g = Sentier:NewGuide("rep-a", { title = "A", category = "R", catalog = { [1] = { title = "Q" } } })
    assert.is_true(g:Quest(999, {}).missing)
    assert.is_nil(g:Quest(1, {}).missing)
  end)

  it("utilise la faction donnée aux quêtes mondiales, sinon celle du guide", function()
    local g = Sentier:NewGuide("rep-a", { title = "A", category = "R", faction = 2696 })
    assert.are.same({ 1111 }, g:WorldQuests({ faction = 1111 }).factions)
    local h = Sentier:NewGuide("rep-b", { title = "B", category = "R", faction = 2696 })
    assert.are.same({ 2696 }, h:WorldQuests({}).factions)
  end)

  it("ne lève pas d'erreur sans titre ni catégorie et note un problème", function()
    local g
    assert.has_no.errors(function() g = Sentier:NewGuide("sans-titre", {}) end)
    assert.are.equal("sans-titre", g.title)
    assert.are.equal(ns.L.DEFAULT_CATEGORY, g.category)
    assert.is_true(H.hasProblem(ns, "Guide invalide : sans-titre"))
  end)

  it("donne les bons réglages par défaut à chaque type de tâche", function()
    local g = Sentier:NewGuide("rep-a", { title = "A", category = "R", faction = 2696 })
    local w = g:Weekly("delves", { title = "Gouffres" })
    local d = g:Daily("d", { title = "Jour" })
    local r = g:Rare("rare-x", { questId = 77, title = "Rare" })
    local wq = g:WorldQuests({ zones = { "Harandar" } })
    assert.are.same({ "weekly", "weekly", "weekly" }, { w.type, w.source, w.reset })
    assert.are.same({ "daily", "daily", "daily" }, { d.type, d.source, d.reset })
    assert.are.same({ "rare", "rares", "daily" }, { r.type, r.source, r.reset })
    assert.are.same({ 77 }, r.questIds)
    assert.are.same({ "worldquests", "worldquests", "worldquests" }, { wq.type, wq.source, wq.key })
    assert.are.equal("Quêtes mondiales actives", wq.title)
  end)

  it("signale une tâche en double et garde la première", function()
    local g = Sentier:NewGuide("rep-a", { title = "A", category = "R" })
    local first = g:Weekly("w", { title = "Un" })
    g:Weekly("w", { title = "Deux" })
    assert.are.equal(1, #g.tasks)
    assert.are.equal(first, g.byId["w"])
    assert.is_true(H.hasProblem(ns, "Tâche en double dans rep-a : w"))
  end)

  it("construit l'ordre et ignore les tâches inconnues", function()
    local g = Sentier:NewGuide("rep-a", { title = "A", category = "R", catalog = { [1] = { title = "Q" } } })
    g:Quest(1, {})
    g:Weekly("w", { title = "W" })
    g:Order({ "w", 1, "inconnue" })
    assert.are.equal(2, #g.order)
    assert.are.equal("w", g.order[1].key)
    assert.are.equal("1", g.order[2].key)
    assert.is_true(H.hasProblem(ns, "Ordre de rep-a : tâche inconnue inconnue"))
  end)

  it("ne note pas deux fois le même problème", function()
    ns.Registry:Problem("x")
    ns.Registry:Problem("x")
    assert.are.equal(1, #ns.Registry.problems)
  end)
  it("ne lève pas d'erreur pour une quête absente au numéro non numérique", function()
    local g = Sentier:NewGuide("rep-a", { title = "A", category = "R" })
    local t
    assert.has_no.errors(function() t = g:Quest("abc", {}) end)
    assert.is_true(t.missing)
    assert.is_true(H.hasProblem(ns, "Quête absente du catalogue : abc (rep-a)"))
  end)
end)
